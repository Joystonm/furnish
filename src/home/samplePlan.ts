/**
 * A real plan, generated on this page.
 *
 * The hero on the home page shows a floor plan, and a marketing page that
 * illustrates its product with a drawing nobody produced is a drawing that can
 * drift from the product — or quietly promise something the code does not do.
 * So this calls the same generator the studio calls, on the same brief the
 * studio's "Load the sample plan" uses, and renders the result through the
 * same SVG exporter the Export button uses.
 *
 * If `generateFromBrief` or `planToSvg` changes, this hero changes with it. If
 * they break, this page throws at render rather than showing a stale picture.
 *
 * Nothing here touches the network, the model, or the user's saved projects.
 */
import { planToSvg } from '../export/planSvg.ts';
import { SAMPLE_BRIEF, sampleProject } from '../model/sample.ts';

export interface SamplePlan {
  /** The plan body, ready to drop inside an `<svg>` element. */
  inner: string;
  /** The exporter's millimetre viewBox, so the drawing scales without guessing. */
  viewBox: string;
  plotWidthM: number;
  plotDepthM: number;
  roomCount: number;
  /** Summed area of the rooms actually delivered, in m². */
  floorAreaM2: number;
  /** Rooms that ended up adjacent to a room of the same kind. */
  warnings: string[];
  /** How many storeys the sample house has. */
  storeys: number;
}

/**
 * Runs the generator and slices the exported document down to something inline.
 *
 * `planToSvg` emits a standalone sheet sized in millimetres — correct for the
 * file you download, far too large to put in a `<div>`. So the document is
 * parsed rather than pattern-matched, the root's viewBox is kept verbatim, and
 * only the children are handed back for the page to render at its own size.
 *
 * The markup returned is generated by `planSvg.ts` from the constant brief in
 * `src/model/sample.ts`. It contains no user input and no third-party data,
 * which is why it is inlined rather than sanitised.
 *
 * The sample house has two storeys; the card shows the ground floor of it.
 */
export function buildSamplePlan(): SamplePlan | null {
  const result = sampleProject();
  if (!result.ok) return null;

  const project = result.data.project;
  const floor = project.floors[0];
  if (!floor) return null;

  const sheet = planToSvg(project, floor.id, { furniture: true, labels: true, dimensions: false });
  if (!sheet) return null;

  const root = new DOMParser().parseFromString(sheet, 'image/svg+xml').documentElement;
  if (root.nodeName === 'parsererror' || !root.getAttribute('viewBox')) return null;

  const inner = Array.from(root.childNodes)
    .map((node) => new XMLSerializer().serializeToString(node))
    .join('');

  const rooms = project.rooms.filter((r) => r.floorId === floor.id);

  return {
    inner,
    viewBox: root.getAttribute('viewBox') as string,
    plotWidthM: SAMPLE_BRIEF.plot.width,
    plotDepthM: SAMPLE_BRIEF.plot.depth,
    roomCount: rooms.length,
    floorAreaM2: rooms.reduce((sum, r) => sum + r.width * r.depth, 0),
    warnings: result.data.report.warnings,
    storeys: project.floors.length,
  };
}
